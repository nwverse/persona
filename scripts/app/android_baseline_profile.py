#!/usr/bin/env python3
"""Regenerate the app's Baseline Profile, android/app/src/main/baseline-prof.txt, from a phone (#4055).

    python3 scripts/app/android_baseline_profile.py capture -s <phone> --out /tmp/persona-profile.txt
    python3 scripts/app/android_baseline_profile.py rules /tmp/persona-profile.txt
    python3 scripts/app/android_baseline_profile.py rules a.txt b.txt --mapping <mapping.txt> --out <file> --report <json>

capture needs the release package of the commit being profiled installed on the phone and already inside the app
(paired, or in the demo from the welcome page's "No hub? Try the demo first"). It opens the main pages through
persona://open links in one process, scrolls each, stays in the app so ART's profile saver writes what the JIT saw, then
runs `cmd package dump-profiles` and pulls the text. A phone that does not ART-compile a release package on its own
first is fine; nothing here needs root or a debuggable build.

rules turns one or more dumps into the rule file. The phone reports names after R8: the project keeps names
(-dontobfuscate), but R8 still merges classes, inlines methods into others, narrows signatures and creates synthetic
classes, while AGP hands baseline-prof.txt to R8 as rules about its input. Every name is therefore mapped back through
the release build's mapping.txt (android/app/build/outputs/mapping/release/mapping.txt, from the same commit as the
package on the phone):

    method   the original of the residual method with the same class, name and descriptor
    class    every original class R8 merged into it
    synthetic a method of a class R8 created ($$ExternalSynthetic*, $$Lambda) keeps the source methods inlined into it
             and the class it was made for gets a class rule; R8 recreates the synthetic for that class
    dropped  names the mapping does not explain; their count is printed and written with --report

Rules are exactly what the phone saw: no whole-class wildcards, which in a measurement compiled about twice the code
for no faster start. Dumps come in profman's text (`cmd package dump-profiles` on Android 12 based systems) or already
as rules (`dump-profiles --dump-classes-and-methods` on newer ones); both are read.
"""
import argparse
import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RULES = ROOT / 'android/app/src/main/baseline-prof.txt'
MAPPING = ROOT / 'android/app/build/outputs/mapping/release/mapping.txt'
PACKAGE = 'com.lyinsun.jarvis'
HEADER = '''# The app's Baseline Profile (#4055): classes and methods ART compiles ahead of time on install.
# Generated by scripts/app/android_baseline_profile.py from a release build walked through the demo on a phone;
# regenerate it as docs/android/android.md "Baseline Profile" describes instead of editing it by hand.
'''
# The pages capture walks, in order, in one process.
PAGES = (
    'persona://open?target=tab&tab=agents',
    'persona://open?target=chat&machine=server&session=b2e4d6f8-0000-4000-8000-000000000004&kind=assistant',
    'persona://open?target=chat&machine=macbook&session=a1f3c2d4-0000-4000-8000-000000000009&kind=agent',
    'persona://open?target=tab&tab=inbox',
    'persona://open?target=tab&tab=settings',
    'persona://open?target=tab&tab=persona',
    'persona://open?target=tab&tab=agents',
)
PRIMITIVES = {'void': 'V', 'boolean': 'Z', 'byte': 'B', 'char': 'C', 'short': 'S', 'int': 'I', 'long': 'J',
              'float': 'F', 'double': 'D'}
SECTIONS = {'hot methods:': 'H', 'startup methods:': 'S', 'post startup methods:': 'P', 'classes:': 'C'}
SYNTHETIC = re.compile(r'\$\$(?:ExternalSynthetic|Lambda)')
RULE = re.compile(r'^([HSP]*)(L[^;]+;)(?:->([^(]+)(\(.*))?$')
CLASS_LINE = re.compile(r'^(\S+) -> (\S+):$')
MEMBER_LINE = re.compile(r'^    (?:(\d+):(\d+):)?(\S+) ([^\s(]+)\(([^)]*)\)(?::\d+(?::\d+)?)? -> (\S+)$')


def descriptor(name):
    """A Java type name (`int`, `a.b.C[]`) as a descriptor (`I`, `[La/b/C;`)."""
    name = name.strip()
    dims = 0
    while name.endswith('[]'):
        dims, name = dims + 1, name[:-2]
    return '[' * dims + (PRIMITIVES.get(name) or 'L' + name.replace('.', '/') + ';')


def method_descriptor(params, ret):
    return '(' + ''.join(descriptor(p) for p in params.split(',') if p.strip()) + ')' + descriptor(ret)


def read_dump(text, methods, classes):
    """Adds a dump's methods ({(class, name, descriptor): flags}) and classes (descriptors) to the two collections."""
    section = None
    for line in text.splitlines():
        rule = RULE.match(line.strip())
        if rule and not line.startswith('\t'):
            flags, cls, name, desc = rule.groups()
            if name:
                methods.setdefault((cls, name, desc), set()).update(flags or 'H')
            else:
                classes.add(cls)
            continue
        stripped = line.strip()
        if stripped in SECTIONS:
            section = SECTIONS[stripped]
            continue
        if not line.startswith('\t\t'):
            if not line.startswith('\t'):
                section = None
            continue
        entry = re.sub(r'\[[^\]]*\]$', '', stripped.rstrip(',').strip())
        if section == 'C':
            if not entry.endswith('[]'):
                classes.add(descriptor(entry))
        elif section:
            match = re.match(r'^(\S+) (\S+)\.([^.(]+)\((.*)\)$', entry)
            if match:
                ret, cls, name, params = match.groups()
                methods.setdefault((descriptor(cls), name, method_descriptor(params, ret)), set()).add(section)


class Mapping:
    """What R8's mapping.txt says about each residual class and method."""

    def __init__(self, text):
        self.originals = {}  # residual class -> original classes merged into it
        self.renamed = {}  # original class -> residual class
        self.synthesized = set()  # residual classes R8 created
        self.methods = {}  # (residual class, residual name) -> [entries]
        current, group, entries = None, None, []
        for line in text.splitlines():
            if not line.startswith(' ') and not line.startswith('#'):
                group = None
                match = CLASS_LINE.match(line)
                current = None
                if match:
                    original, residual = descriptor(match.group(1)), descriptor(match.group(2))
                    current = (original, residual)
                    if not match.group(2).startswith('R8$$REMOVED'):
                        self.renamed[original] = residual
                        self.originals.setdefault(residual, []).append(original)
                continue
            if current is None:
                continue
            if line.startswith('#'):
                if '"com.android.tools.r8.synthesized"' in line:
                    self.synthesized.add(current[1])
                continue
            stripped = line.strip()
            if stripped.startswith('#'):
                if group is not None and 'residualsignature' in stripped:
                    try:
                        group['signature'] = json.loads(stripped[1:])['signature']
                    except ValueError:
                        pass
                continue
            match = MEMBER_LINE.match(line)
            if not match:
                group = None  # a field
                continue
            start, end, ret, qualified, params, residual_name = match.groups()
            key = (start, end, residual_name)
            if start is None or group is None or group['key'] != key:
                group = dict(key=key, frames=[], signature=None, cls=current)
                entries.append(group)
            if '.' in qualified:
                cls, name = qualified.rsplit('.', 1)
                cls = descriptor(cls)
            else:
                cls, name = current[0], qualified
            group['frames'].append((cls, name, method_descriptor(params, ret), (params, ret)))
            if start is None:
                group = None
        # R8 writes a changed signature once, under a method's first range; its other ranges have the same outer
        # frame and residual name.
        seen = {}
        for group in entries:
            key = (group['cls'], group['frames'][-1][:3], group['key'][2])
            if group['signature']:
                seen[key] = group['signature']
            else:
                group['signature'] = seen.get(key)
            self.methods.setdefault((group['cls'][1], group['key'][2]), []).append(group)

    def residual_type(self, name):
        dims = name.count('[]')
        base = descriptor(name.replace('[]', ''))
        return '[' * dims + self.renamed.get(base, base)

    def residual_descriptor(self, group):
        if group['signature'] and group['signature'].startswith('('):
            return group['signature']
        params, ret = group['frames'][-1][3]
        return '(' + ''.join(self.residual_type(p) for p in params.split(',') if p.strip()) + ')' + \
            self.residual_type(ret)

    def is_synthetic(self, cls):
        return cls in self.synthesized or bool(SYNTHETIC.search(cls))


def context_class(cls):
    """The class R8 made a synthetic class for (persona/A$$ExternalSyntheticLambda3 -> persona/A), or None for one it
    made on its own (an API stub such as android/text/SegmentFinder)."""
    return SYNTHETIC.split(cls)[0] + ';' if SYNTHETIC.search(cls) else None


def to_rules(mapping, methods, classes):
    """Maps residual names back to originals. Returns ({(class, name, descriptor): flags}, {classes}, stats, dropped)."""
    out_methods, out_classes = {}, set()
    stats = dict(methods=0, methods_kept=0, methods_synthetic=0, methods_dropped=0, classes=0, classes_kept=0,
                 classes_synthetic=0, classes_dropped=0)
    dropped = []
    for (cls, name, desc), flags in sorted(methods.items()):
        stats['methods'] += 1
        groups = [g for g in mapping.methods.get((cls, name), ()) if mapping.residual_descriptor(g) == desc]
        # The outer frame of each range is the method R8 read; frames before it were inlined into it.
        originals = {g['frames'][-1][:3] for g in groups if not mapping.is_synthetic(g['frames'][-1][0])}
        if mapping.is_synthetic(cls):
            # A synthetic method keeps the source lambda bodies R8 moved into it (several when R8 merged lambdas).
            stats['methods_synthetic'] += 1
            for original in originals:
                out_methods.setdefault(original, set()).update(flags)
            out_classes.add(context_class(cls))
            continue
        if not originals and not mapping.methods.get((cls, name)) and mapping.originals.get(cls, [cls]) == [cls]:
            # Not R8's class, or a method the mapping leaves out because R8 kept it as it was (abstract ones).
            originals = {(cls, name, desc)}
        if not originals:
            stats['methods_dropped'] += 1
            dropped.append('%s->%s%s' % (cls, name, desc))
            continue
        stats['methods_kept'] += 1
        for original in originals:
            out_methods.setdefault(original, set()).update(flags)
    for cls in sorted(classes):
        stats['classes'] += 1
        if mapping.is_synthetic(cls):
            stats['classes_synthetic'] += 1
            out_classes.add(context_class(cls))
        elif cls in mapping.originals:
            stats['classes_kept'] += 1
            out_classes.update(mapping.originals[cls])
        elif cls in mapping.renamed:
            stats['classes_dropped'] += 1  # the name of an original class R8 merged away
            dropped.append(cls)
        else:
            stats['classes_kept'] += 1
            out_classes.add(cls)
    out_classes = {c for c in out_classes if c and not mapping.is_synthetic(c)}
    return out_methods, out_classes, stats, dropped


def write_rules(path, out_methods, out_classes):
    lines = sorted(out_classes)
    lines += sorted(''.join(f for f in 'HSP' if f in flags) + '%s->%s%s' % key for key, flags in out_methods.items())
    Path(path).write_text(HEADER + ''.join(line + '\n' for line in lines))
    return len(lines)


def rules(args):
    methods, classes = {}, set()
    for dump in args.dumps:
        read_dump(Path(dump).read_text(encoding='utf-8', errors='replace'), methods, classes)
    if args.only:
        prefix = 'L' + args.only.replace('.', '/')
        methods = {k: v for k, v in methods.items() if k[0].startswith(prefix)}
        classes = {c for c in classes if c.startswith(prefix)}
    mapping = Mapping(Path(args.mapping).read_text(encoding='utf-8'))
    out_methods, out_classes, stats, dropped = to_rules(mapping, methods, classes)
    stats['rules'] = write_rules(args.out, out_methods, out_classes)
    stats['app_rules'] = sum(1 for c in out_classes if c.startswith('Lpersona/')) + \
        sum(1 for k in out_methods if k[0].startswith('Lpersona/'))
    if args.report:
        Path(args.report).write_text(json.dumps(dict(stats=stats, dropped=dropped), indent=1) + '\n')
    print(json.dumps(stats))
    print('wrote %d rules to %s; %d methods and %d classes the mapping does not explain were dropped'
          % (stats['rules'], args.out, stats['methods_dropped'], stats['classes_dropped']), file=sys.stderr)


def capture(args):
    def adb(*command):
        return subprocess.run(['adb', '-s', args.serial, *command], check=True, capture_output=True,
                              text=True).stdout

    w, h = map(int, re.findall(r'(\d+)x(\d+)', adb('shell', 'wm', 'size'))[-1])

    def scroll():
        for y1, y2 in ((h * 78 // 100, h * 28 // 100), (h * 28 // 100, h * 78 // 100)):
            for _ in range(3):
                adb('shell', 'input', 'swipe', str(w // 2), str(y1), str(w // 2), str(y2), '180')
                time.sleep(0.9)

    adb('shell', 'am', 'start', '-W', '-n', PACKAGE + '/persona.android.MainActivity')
    time.sleep(4)
    scroll()
    for link in PAGES:
        print('open ' + link, file=sys.stderr)
        adb('shell', 'am', 'start', '-W', '-a', 'android.intent.action.VIEW', '-d', "'%s'" % link, PACKAGE)
        time.sleep(3)
        scroll()
    print('staying %d s for the profile saver' % args.dwell, file=sys.stderr)
    time.sleep(args.dwell)
    adb('shell', 'input', 'keyevent', 'KEYCODE_HOME')
    time.sleep(15)
    adb('shell', 'cmd', 'package', 'dump-profiles', PACKAGE)
    adb('pull', '/data/misc/profman/%s-primary.prof.txt' % PACKAGE, args.out)
    print('pulled ' + args.out, file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = parser.add_subparsers(dest='command', required=True)
    c = sub.add_parser('capture', help='walk the main pages on a phone and pull its profile dump')
    c.add_argument('-s', dest='serial', required=True)
    c.add_argument('--out', required=True)
    c.add_argument('--dwell', type=int, default=90, help='seconds to stay in the app before dumping (90)')
    r = sub.add_parser('rules', help='turn dumps into baseline-prof.txt')
    r.add_argument('dumps', nargs='+')
    r.add_argument('--mapping', default=str(MAPPING))
    r.add_argument('--out', default=str(RULES))
    r.add_argument('--report', help='write counts and the dropped names as JSON')
    r.add_argument('--only', help='keep only names under this package prefix, for example persona.')
    args = parser.parse_args()
    capture(args) if args.command == 'capture' else rules(args)


if __name__ == '__main__':
    main()
