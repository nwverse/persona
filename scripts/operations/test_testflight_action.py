"""TestFlight retries must reuse uploaded builds and verify Internal availability."""
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import types
import unittest
from unittest.mock import patch

PATH = Path(__file__).with_name("testflight_action.py")
spec = importlib.util.spec_from_file_location("testflight_action", PATH)
action = importlib.util.module_from_spec(spec)
spec.loader.exec_module(action)


class TestFlightActionTests(unittest.TestCase):
    def invoke(self, home, phase, visible=True, remote_build=True):
        state = Path(home) / "testflight-checkpoint.json"
        state.write_text(json.dumps({"commit": "a" * 40, "build": "100", "phase": phase}))
        build = {"id": "build-id", "attributes": {"processingState": "VALID"}}
        remote = [build] if remote_build else []
        asc = types.SimpleNamespace(
            build_by_version=lambda number: remote[0] if remote else None,
            group_id=lambda: "group-id",
            request=lambda *args: {"data": {"attributes": {"hasAccessToAllBuilds": visible}}},
            get_all=lambda *args: [],
        )
        argv = [str(PATH), "--repo", home, "--worktree", home + "/worktree", "--state-dir", home, "--commit", "a" * 40]
        with patch.dict(os.environ, PERSONA_OPERATION_RELEASE_LOCKED="1"), patch.object(sys, "argv", argv), \
                patch.object(action, "prepare"), patch.object(action, "run", side_effect=lambda *args: remote.append(build) if not remote else None) as run, \
                patch.object(action.subprocess, "call", return_value=0) as upload, patch.dict(sys.modules, asc_testflight=asc):
            result = action.main()
            if remote_build:
                upload.assert_not_called()
                self.assertEqual(len(remote), 1)
            else:
                upload.assert_called_once()
                self.assertEqual(len(remote), 1)
            run.assert_called_once()
            self.assertEqual(run.call_args.args[0][-3:], ["wait", "45", "100"])
        self.assertEqual(result, 0)
        self.assertEqual(json.loads(state.read_text())["phase"], "complete")

    def test_uploaded_build_is_not_uploaded_again(self):
        with tempfile.TemporaryDirectory() as home:
            self.invoke(home, "uploaded")

    def test_interrupted_upload_found_remotely_is_resumed(self):
        with tempfile.TemporaryDirectory() as home:
            self.invoke(home, "upload_started")

    def test_interrupted_upload_not_found_remotely_is_retried(self):
        with tempfile.TemporaryDirectory() as home:
            self.invoke(home, "upload_started", remote_build=False)

    def test_available_build_after_upload_error_is_resumed(self):
        with tempfile.TemporaryDirectory() as home:
            self.invoke(home, "upload_failed")

    def test_inherited_operation_lock_does_not_wrap_the_action_again(self):
        argv = [str(PATH), "--repo", "/repo", "--worktree", "/worktree", "--state-dir", "/state", "--commit", "a" * 40]
        with patch.dict(os.environ, PERSONA_OPERATION_LOCKS='{"release": true}', clear=True), \
                patch.object(sys, "argv", argv), patch.object(action, "prepare") as prepare, \
                patch.object(action.Path, "mkdir", side_effect=RuntimeError("action body reached")), \
                patch.object(action.subprocess, "call", side_effect=RuntimeError("unexpected wrapper")):
            with self.assertRaisesRegex(RuntimeError, "action body reached"):
                action.main()
        prepare.assert_called_once_with(Path("/repo"), Path("/worktree"), "a" * 40)

    def test_generated_xcodegen_project_does_not_make_a_release_worktree_dirty(self):
        with tempfile.TemporaryDirectory() as home:
            root = Path(home)
            subprocess.run(["git", "init", "-q", str(root)], check=True)
            project = root / "apple/Persona.xcodeproj"
            project.mkdir(parents=True)
            (project / "project.pbxproj").write_text("// generated by XcodeGen\n")
            (root / ".gitignore").write_text((PATH.parents[2] / ".gitignore").read_text())
            self.assertEqual(subprocess.check_output(
                ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=all", "--", "apple"],
                text=True,
            ), "")


    def test_internal_visibility_is_required(self):
        with tempfile.TemporaryDirectory() as home:
            with self.assertRaisesRegex(RuntimeError, "Internal"):
                self.invoke(home, "uploaded", visible=False)
            self.assertEqual(json.loads((Path(home) / "testflight-checkpoint.json").read_text())["phase"], "uploaded")


if __name__ == "__main__":
    unittest.main()
