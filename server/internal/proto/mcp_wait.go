package proto

// MCPWaitKind is the live, content-free state of a pending MCP tool call. It is deliberately a closed enum: no tool,
// interaction, machine or account content belongs in this signal. Unknown values normalize to MCPWaitUnknown so a
// receiver on a rolling upgrade always uses its conservative fallback.
type MCPWaitKind string

const (
	MCPWaitUnknown  MCPWaitKind = "unknown"
	MCPWaitApproval MCPWaitKind = "approval"
	MCPWaitAnswer   MCPWaitKind = "answer"
	MCPWaitComputer MCPWaitKind = "computer"
)

// EventMCPWait carries one pending call's current kind through the existing device-notification relay.
const EventMCPWait = "mcp.wait"

// MCPWaitEvent is EventMCPWait's complete params. CallID is an opaque correlator generated by the local node; Kind
// is the only state. No interaction content, tool name or routing name is part of this payload.
type MCPWaitEvent struct {
	CallID string      `json:"call_id"`
	Kind   MCPWaitKind `json:"kind"`
}

// NormalizeMCPWaitKind keeps a known enum value and maps every other value to unknown.
func NormalizeMCPWaitKind(kind MCPWaitKind) MCPWaitKind {
	switch kind {
	case MCPWaitApproval, MCPWaitAnswer, MCPWaitComputer:
		return kind
	default:
		return MCPWaitUnknown
	}
}
